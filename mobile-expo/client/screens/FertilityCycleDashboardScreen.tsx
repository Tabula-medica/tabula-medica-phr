import React, { useState } from "react";
import {
  View,
  ScrollView,
  Pressable,
  StyleSheet,
  ActivityIndicator,
  Share,
  Platform,
} from "react-native";
import { Feather } from "@expo/vector-icons";
import { useQuery } from "@tanstack/react-query";
import { useTheme } from "@/hooks/useTheme";
import { useHeaderHeight } from "@react-navigation/elements";
import { useSafeAreaInsets } from "react-native-safe-area-context";
import { ThemedText } from "@/components/ThemedText";
import { ThemedView } from "@/components/ThemedView";
import { Spacing, BorderRadius } from "@/constants/theme";
import Animated, { FadeInDown } from "react-native-reanimated";

type TabType = "dashboard" | "hormones" | "provider" | "confidence";

const TABS: { key: TabType; label: string; icon: keyof typeof Feather.glyphMap; color: string }[] = [
  { key: "dashboard", label: "Cycle", icon: "target", color: "#EC4899" },
  { key: "hormones", label: "MIRA", icon: "activity", color: "#8B5CF6" },
  { key: "provider", label: "Share", icon: "share-2", color: "#3B82F6" },
  { key: "confidence", label: "Insights", icon: "trending-up", color: "#10B981" },
];

export default function FertilityCycleDashboardScreen() {
  const { theme: colors, isDark } = useTheme();
  const headerHeight = useHeaderHeight();
  const insets = useSafeAreaInsets();
  const [activeTab, setActiveTab] = useState<TabType>("dashboard");
  const [expandedPhase, setExpandedPhase] = useState<string | null>(null);
  const [expandedHormone, setExpandedHormone] = useState<string | null>(null);
  const [expandedMetric, setExpandedMetric] = useState<string | null>(null);

  const { data, isLoading } = useQuery<any>({
    queryKey: ["/api/womens-health/fertility-cycle"],
  });

  const togglePhase = (id: string) => setExpandedPhase(expandedPhase === id ? null : id);
  const toggleHormone = (id: string) => setExpandedHormone(expandedHormone === id ? null : id);
  const toggleMetric = (id: string) => setExpandedMetric(expandedMetric === id ? null : id);

  const handleShareReport = async () => {
    try {
      await Share.share({
        title: "Fertility Cycle Report",
        message: "My Fertility Cycle Report from Tabula Medica\n\nThis report contains cycle tracking data collected via MIRA at-home hormone monitoring. Please review the attached hormone trends, ovulation confirmations, and cycle regularity metrics for personalized fertility coaching.\n\nGenerated by Tabula Medica - tabulamedica.health",
      });
    } catch (e) {}
  };

  const renderDashboardTab = () => {
    if (!data) return null;
    return (
      <View>
        <Animated.View entering={FadeInDown.delay(100)} style={[styles.heroCard, { backgroundColor: isDark ? "#1E1030" : "#FDF2F8" }]}>
          <View style={[styles.heroIconContainer, { backgroundColor: "#EC489920" }]}>
            <Feather name="target" size={32} color="#EC4899" />
          </View>
          <ThemedText style={[styles.heroTitle, { color: colors.text }]}>Fertility Cycle Optimization</ThemedText>
          <ThemedText style={[styles.heroSubtitle, { color: colors.textSecondary }]}>
            Track your cycle phases, hormones, and fertile window with MIRA at-home monitoring for personalized fertility coaching
          </ThemedText>
        </Animated.View>

        <Animated.View entering={FadeInDown.delay(200)}>
          <ThemedText style={[styles.sectionTitle, { color: colors.text }]}>Cycle Phases</ThemedText>
          <ThemedText style={[styles.sectionSubtitle, { color: colors.textSecondary }]}>
            Understanding each phase helps optimize timing and identify patterns
          </ThemedText>
        </Animated.View>

        {data.cyclePhases?.map((phase: any, index: number) => (
          <Animated.View key={phase.phase} entering={FadeInDown.delay(300 + index * 80)}>
            <Pressable
              testID={`phase-card-${index}`}
              onPress={() => togglePhase(phase.phase)}
              style={[styles.phaseCard, { backgroundColor: isDark ? colors.backgroundSecondary : colors.backgroundDefault, borderLeftColor: phase.color }]}
            >
              <View style={styles.phaseHeader}>
                <View style={[styles.fertilityBadge, { backgroundColor: phase.color + "20" }]}>
                  <ThemedText style={[styles.fertilityBadgeText, { color: phase.color }]}>{phase.fertility}</ThemedText>
                </View>
                <View style={styles.phaseHeaderText}>
                  <ThemedText style={[styles.phaseName, { color: colors.text }]}>{phase.phase}</ThemedText>
                  <ThemedText style={[styles.phaseDays, { color: colors.textSecondary }]}>{phase.days}</ThemedText>
                </View>
                <Feather name={expandedPhase === phase.phase ? "chevron-up" : "chevron-down"} size={20} color={colors.textSecondary} />
              </View>

              {expandedPhase === phase.phase ? (
                <View style={styles.phaseDetails}>
                  <View style={styles.detailRow}>
                    <Feather name="activity" size={14} color={phase.color} />
                    <ThemedText style={[styles.detailLabel, { color: colors.textSecondary }]}>Hormones</ThemedText>
                  </View>
                  <ThemedText style={[styles.detailText, { color: colors.text }]}>{phase.hormoneProfile}</ThemedText>

                  <View style={[styles.detailRow, { marginTop: Spacing.md }]}>
                    <Feather name="thermometer" size={14} color={phase.color} />
                    <ThemedText style={[styles.detailLabel, { color: colors.textSecondary }]}>BBT Range</ThemedText>
                  </View>
                  <ThemedText style={[styles.detailText, { color: colors.text }]}>{phase.bodyTemp}</ThemedText>

                  <View style={[styles.detailRow, { marginTop: Spacing.md }]}>
                    <Feather name="droplet" size={14} color={phase.color} />
                    <ThemedText style={[styles.detailLabel, { color: colors.textSecondary }]}>Cervical Mucus</ThemedText>
                  </View>
                  <ThemedText style={[styles.detailText, { color: colors.text }]}>{phase.cervicalMucus}</ThemedText>

                  <View style={[styles.miraInsightBox, { backgroundColor: phase.color + "10", borderColor: phase.color + "30" }]}>
                    <Feather name="cpu" size={14} color={phase.color} />
                    <ThemedText style={[styles.miraInsightText, { color: colors.text }]}>{phase.miraInsight}</ThemedText>
                  </View>

                  <ThemedText style={[styles.optimizationTitle, { color: colors.text }]}>Optimization Tips</ThemedText>
                  {phase.optimization?.map((tip: string, i: number) => (
                    <View key={i} style={styles.tipRow}>
                      <View style={[styles.tipDot, { backgroundColor: phase.color }]} />
                      <ThemedText style={[styles.tipText, { color: colors.textSecondary }]}>{tip}</ThemedText>
                    </View>
                  ))}
                </View>
              ) : null}
            </Pressable>
          </Animated.View>
        ))}

        <Animated.View entering={FadeInDown.delay(700)}>
          <ThemedText style={[styles.sectionTitle, { color: colors.text }]}>Key Fertility Indicators</ThemedText>
        </Animated.View>

        {data.fertilityMetrics?.metrics?.map((metric: any, index: number) => (
          <Animated.View key={metric.name} entering={FadeInDown.delay(800 + index * 60)}>
            <Pressable
              testID={`metric-card-${index}`}
              onPress={() => toggleMetric(metric.name)}
              style={[styles.metricCard, { backgroundColor: isDark ? colors.backgroundSecondary : colors.backgroundDefault }]}
            >
              <View style={styles.metricHeader}>
                <View style={[styles.metricIcon, { backgroundColor: "#EC489915" }]}>
                  <Feather name={metric.icon as any} size={18} color="#EC4899" />
                </View>
                <View style={styles.metricHeaderText}>
                  <ThemedText style={[styles.metricName, { color: colors.text }]}>{metric.name}</ThemedText>
                  <ThemedText style={[styles.metricRange, { color: "#10B981" }]}>{metric.idealRange}</ThemedText>
                </View>
                <Feather name={expandedMetric === metric.name ? "chevron-up" : "chevron-down"} size={18} color={colors.textSecondary} />
              </View>

              {expandedMetric === metric.name ? (
                <View style={styles.metricDetails}>
                  <ThemedText style={[styles.detailText, { color: colors.text }]}>{metric.description}</ThemedText>
                  <View style={[styles.redFlagBox, { backgroundColor: "#EF444410", borderColor: "#EF444430" }]}>
                    <Feather name="alert-triangle" size={14} color="#EF4444" />
                    <ThemedText style={[styles.redFlagText, { color: "#EF4444" }]}>{metric.redFlag}</ThemedText>
                  </View>
                </View>
              ) : null}
            </Pressable>
          </Animated.View>
        ))}

        <Animated.View entering={FadeInDown.delay(1100)}>
          <ThemedText style={[styles.sectionTitle, { color: colors.text }]}>When to See a Specialist</ThemedText>
        </Animated.View>

        {data.whenToSeeSpecialist?.criteria?.map((item: any, index: number) => (
          <Animated.View key={index} entering={FadeInDown.delay(1200 + index * 50)}>
            <View style={[styles.specialistCard, { backgroundColor: isDark ? colors.backgroundSecondary : colors.backgroundDefault }]}>
              <View style={styles.specialistRow}>
                <Feather name="alert-circle" size={16} color={item.urgency.includes("Proactive") ? "#F59E0B" : "#EF4444"} />
                <View style={styles.specialistText}>
                  <ThemedText style={[styles.specialistCondition, { color: colors.text }]}>{item.condition}</ThemedText>
                  <ThemedText style={[styles.specialistUrgency, { color: item.urgency.includes("Proactive") ? "#F59E0B" : "#EF4444" }]}>{item.urgency}</ThemedText>
                </View>
              </View>
            </View>
          </Animated.View>
        ))}
      </View>
    );
  };

  const renderHormonesTab = () => {
    if (!data?.miraHormones) return null;
    return (
      <View>
        <Animated.View entering={FadeInDown.delay(100)} style={[styles.heroCard, { backgroundColor: isDark ? "#1A1030" : "#F5F3FF" }]}>
          <View style={[styles.heroIconContainer, { backgroundColor: "#8B5CF620" }]}>
            <Feather name="cpu" size={32} color="#8B5CF6" />
          </View>
          <ThemedText style={[styles.heroTitle, { color: colors.text }]}>{data.miraHormones.title}</ThemedText>
          <ThemedText style={[styles.heroSubtitle, { color: colors.textSecondary }]}>{data.miraHormones.description}</ThemedText>
        </Animated.View>

        {data.miraHormones.hormones?.map((hormone: any, index: number) => (
          <Animated.View key={hormone.name} entering={FadeInDown.delay(200 + index * 100)}>
            <Pressable
              testID={`hormone-card-${index}`}
              onPress={() => toggleHormone(hormone.name)}
              style={[styles.hormoneCard, { backgroundColor: isDark ? colors.backgroundSecondary : colors.backgroundDefault }]}
            >
              <View style={styles.hormoneHeader}>
                <View style={[styles.hormoneIcon, { backgroundColor: "#8B5CF615" }]}>
                  <Feather name="activity" size={20} color="#8B5CF6" />
                </View>
                <View style={styles.hormoneHeaderText}>
                  <ThemedText style={[styles.hormoneName, { color: colors.text }]}>{hormone.name}</ThemedText>
                  <ThemedText style={[styles.hormoneRole, { color: colors.textSecondary }]} numberOfLines={expandedHormone === hormone.name ? undefined : 1}>{hormone.role}</ThemedText>
                </View>
                <Feather name={expandedHormone === hormone.name ? "chevron-up" : "chevron-down"} size={18} color={colors.textSecondary} />
              </View>

              {expandedHormone === hormone.name ? (
                <View style={styles.hormoneDetails}>
                  <View style={[styles.hormoneRangeBox, { backgroundColor: "#10B98110" }]}>
                    <ThemedText style={[styles.hormoneRangeLabel, { color: "#10B981" }]}>Normal Range</ThemedText>
                    <ThemedText style={[styles.hormoneRangeValue, { color: colors.text }]}>{hormone.normalRange}</ThemedText>
                  </View>

                  <View style={[styles.miraInsightBox, { backgroundColor: "#8B5CF610", borderColor: "#8B5CF630" }]}>
                    <Feather name="cpu" size={14} color="#8B5CF6" />
                    <ThemedText style={[styles.miraInsightText, { color: colors.text }]}>{hormone.trackingTip}</ThemedText>
                  </View>

                  <View style={styles.loincRow}>
                    <Feather name="hash" size={12} color={colors.textSecondary} />
                    <ThemedText style={[styles.loincCode, { color: colors.textSecondary }]}>{hormone.clinicalCode}</ThemedText>
                  </View>
                </View>
              ) : null}
            </Pressable>
          </Animated.View>
        ))}
      </View>
    );
  };

  const renderProviderTab = () => {
    if (!data?.providerShareTemplate) return null;
    return (
      <View>
        <Animated.View entering={FadeInDown.delay(100)} style={[styles.heroCard, { backgroundColor: isDark ? "#0F1A30" : "#EFF6FF" }]}>
          <View style={[styles.heroIconContainer, { backgroundColor: "#3B82F620" }]}>
            <Feather name="share-2" size={32} color="#3B82F6" />
          </View>
          <ThemedText style={[styles.heroTitle, { color: colors.text }]}>{data.providerShareTemplate.title}</ThemedText>
          <ThemedText style={[styles.heroSubtitle, { color: colors.textSecondary }]}>{data.providerShareTemplate.description}</ThemedText>
        </Animated.View>

        <Animated.View entering={FadeInDown.delay(200)}>
          <ThemedText style={[styles.sectionTitle, { color: colors.text }]}>Report Contents</ThemedText>
          <View style={[styles.reportContentsCard, { backgroundColor: isDark ? colors.backgroundSecondary : colors.backgroundDefault }]}>
            {data.providerShareTemplate.sections?.map((section: string, index: number) => (
              <View key={index} style={styles.reportRow}>
                <View style={[styles.reportNumber, { backgroundColor: "#3B82F615" }]}>
                  <ThemedText style={[styles.reportNumberText, { color: "#3B82F6" }]}>{index + 1}</ThemedText>
                </View>
                <ThemedText style={[styles.reportText, { color: colors.text }]}>{section}</ThemedText>
              </View>
            ))}
          </View>
        </Animated.View>

        <Animated.View entering={FadeInDown.delay(300)}>
          <ThemedText style={[styles.sectionTitle, { color: colors.text }]}>Sharing Methods</ThemedText>
          {data.providerShareTemplate.sharingMethods?.map((method: any, index: number) => (
            <View key={index} style={[styles.shareMethodCard, { backgroundColor: isDark ? colors.backgroundSecondary : colors.backgroundDefault }]}>
              <View style={[styles.shareMethodIcon, { backgroundColor: "#3B82F615" }]}>
                <Feather name={index === 0 ? "file-text" : index === 1 ? "database" : "link"} size={20} color="#3B82F6" />
              </View>
              <View style={styles.shareMethodText}>
                <ThemedText style={[styles.shareMethodName, { color: colors.text }]}>{method.method}</ThemedText>
                <ThemedText style={[styles.shareMethodDesc, { color: colors.textSecondary }]}>{method.description}</ThemedText>
              </View>
            </View>
          ))}
        </Animated.View>

        <Animated.View entering={FadeInDown.delay(400)}>
          <Pressable
            testID="button-share-report"
            onPress={handleShareReport}
            style={[styles.shareButton, { backgroundColor: "#3B82F6" }]}
          >
            <Feather name="share" size={18} color="#FFFFFF" />
            <ThemedText style={styles.shareButtonText}>Share Report with Provider</ThemedText>
          </Pressable>
        </Animated.View>
      </View>
    );
  };

  const renderConfidenceTab = () => {
    if (!data?.confidenceFactors) return null;
    return (
      <View>
        <Animated.View entering={FadeInDown.delay(100)} style={[styles.heroCard, { backgroundColor: isDark ? "#0A1F1A" : "#F0FDF4" }]}>
          <View style={[styles.heroIconContainer, { backgroundColor: "#10B98120" }]}>
            <Feather name="trending-up" size={32} color="#10B981" />
          </View>
          <ThemedText style={[styles.heroTitle, { color: colors.text }]}>{data.confidenceFactors.title}</ThemedText>
          <ThemedText style={[styles.heroSubtitle, { color: colors.textSecondary }]}>
            Evidence-based insights to support your fertility journey
          </ThemedText>
        </Animated.View>

        {data.confidenceFactors.factors?.map((factor: any, index: number) => (
          <Animated.View key={factor.category} entering={FadeInDown.delay(200 + index * 100)}>
            <View style={[styles.confidenceCard, { backgroundColor: isDark ? colors.backgroundSecondary : colors.backgroundDefault }]}>
              <View style={[styles.confidenceCategory, { backgroundColor: "#10B98115" }]}>
                <ThemedText style={[styles.confidenceCategoryText, { color: "#10B981" }]}>{factor.category}</ThemedText>
              </View>
              <ThemedText style={[styles.confidenceInsight, { color: colors.text }]}>{factor.insight}</ThemedText>
              <View style={[styles.statisticBox, { backgroundColor: isDark ? "#10B98108" : "#F0FDF4", borderColor: "#10B98130" }]}>
                <Feather name="bar-chart-2" size={14} color="#10B981" />
                <ThemedText style={[styles.statisticText, { color: colors.textSecondary }]}>{factor.statistic}</ThemedText>
              </View>
            </View>
          </Animated.View>
        ))}

        <Animated.View entering={FadeInDown.delay(700)}>
          <View style={[styles.disclaimerCard, { backgroundColor: isDark ? "#1A1510" : "#FFFBEB", borderColor: "#F59E0B30" }]}>
            <Feather name="info" size={16} color="#F59E0B" />
            <ThemedText style={[styles.disclaimerText, { color: colors.textSecondary }]}>
              This information is for educational purposes only and does not constitute medical advice. Always consult your healthcare provider for personalized fertility guidance.
            </ThemedText>
          </View>
        </Animated.View>
      </View>
    );
  };

  return (
    <ThemedView style={styles.container}>
      <ScrollView
        contentContainerStyle={[styles.scrollContent, { paddingTop: headerHeight + Spacing.md, paddingBottom: insets.bottom + Spacing["2xl"] }]}
        showsVerticalScrollIndicator={false}
      >
        <View style={styles.tabContainer}>
          {TABS.map((tab) => {
            const isActive = activeTab === tab.key;
            return (
              <Pressable
                key={tab.key}
                testID={`tab-${tab.key}`}
                onPress={() => setActiveTab(tab.key)}
                style={[
                  styles.tab,
                  { backgroundColor: isActive ? tab.color + "15" : "transparent", borderColor: isActive ? tab.color : "transparent" },
                ]}
              >
                <Feather name={tab.icon} size={16} color={isActive ? tab.color : colors.textSecondary} />
                <ThemedText style={[styles.tabLabel, { color: isActive ? tab.color : colors.textSecondary, fontWeight: isActive ? "600" : "400" }]}>
                  {tab.label}
                </ThemedText>
              </Pressable>
            );
          })}
        </View>

        {isLoading ? (
          <View style={styles.loadingContainer}>
            <ActivityIndicator size="large" color="#EC4899" />
            <ThemedText style={[styles.loadingText, { color: colors.textSecondary }]}>Loading fertility data...</ThemedText>
          </View>
        ) : (
          <View>
            {activeTab === "dashboard" ? renderDashboardTab() : null}
            {activeTab === "hormones" ? renderHormonesTab() : null}
            {activeTab === "provider" ? renderProviderTab() : null}
            {activeTab === "confidence" ? renderConfidenceTab() : null}
          </View>
        )}
      </ScrollView>
    </ThemedView>
  );
}

