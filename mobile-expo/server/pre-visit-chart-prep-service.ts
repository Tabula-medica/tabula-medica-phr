/**
 * Pre-Visit Chart Prep Service — Roadmap item 2.5
 *
 * Nightly batch or on-demand: for a scheduled appointment, uses Vertex AI /
 * Claude (extended thinking) to produce a one-screen provider brief:
 *   - Active problems + recent changes
 *   - Medication changes since last visit
 *   - Overdue health maintenance (screenings, immunizations, labs)
 *   - HCC / MIPS gap suggestions (labeled as suggestions only — never auto-submit)
 *
 * Path: BAA-covered GCP Vertex AI only. Input data is de-identified before the
 * LLM call. No write actions — read-only over the patient chart.
 *
 * FDA guardrail: results are labeled as "clinical suggestions for provider review"
 * and must never be displayed as diagnoses or auto-committed to the record.
 */

import { chatComplete } from "./ai-client";

export interface AppointmentContext {
  appointmentId: string;
  patientId: string;
  patientAgeYears: number;
  patientSex: string;
  appointmentDate: string;
  appointmentType: string;
  providerId?: string;
}

export interface ChartSummaryInput {
  activeProblems: string[];
  currentMedications: { name: string; dose: string; startDate?: string }[];
  recentLabResults: { test: string; value: string; date: string; flag?: string }[];
  lastVisitDate?: string;
  lastVisitNotes?: string;
  dueScreenings?: string[];
  dueImmunizations?: string[];
  allergies?: string[];
}

export interface PreVisitBrief {
  appointmentId: string;
  patientId: string;
  generatedAt: string;
  modelUsed: string;
  activeProblems: string[];
  medicationChanges: string[];
  overdueHealthMaintenance: string[];
  hccGapSuggestions: string[];
  mipsGapSuggestions: string[];
  priorityAlerts: string[];
  briefSummary: string;
  disclaimer: string;
}

const DISCLAIMER =
  "These suggestions are generated by AI for provider review only. " +
  "They do not constitute a diagnosis, treatment recommendation, or medical order. " +
  "Clinical judgment must be applied before acting on any suggestion. " +
  "HCC/MIPS gap items are administrative suggestions only and require provider verification.";

function deidentifyForLLM(ctx: AppointmentContext, chart: ChartSummaryInput): string {
  const lines: string[] = [
    `Patient age: ${ctx.patientAgeYears} years`,
    `Sex: ${ctx.patientSex}`,
    `Appointment type: ${ctx.appointmentType}`,
    `Appointment date: ${ctx.appointmentDate}`,
    "",
    "ACTIVE PROBLEMS:",
    ...chart.activeProblems.map((p) => `  - ${p}`),
    "",
    "CURRENT MEDICATIONS:",
    ...chart.currentMedications.map(
      (m) => `  - ${m.name} ${m.dose}${m.startDate ? ` (since ${m.startDate})` : ""}`
    ),
    "",
    "RECENT LAB RESULTS (last 90 days):",
    ...chart.recentLabResults.map(
      (l) => `  - ${l.test}: ${l.value} on ${l.date}${l.flag ? ` [${l.flag}]` : ""}`
    ),
  ];

  if (chart.lastVisitDate) {
    lines.push("", `LAST VISIT: ${chart.lastVisitDate}`);
  }

  if (chart.dueScreenings?.length) {
    lines.push("", "DUE SCREENINGS:", ...chart.dueScreenings.map((s) => `  - ${s}`));
  }
  if (chart.dueImmunizations?.length) {
    lines.push("", "DUE IMMUNIZATIONS:", ...chart.dueImmunizations.map((i) => `  - ${i}`));
  }
  if (chart.allergies?.length) {
    lines.push("", "ALLERGIES:", ...chart.allergies.map((a) => `  - ${a}`));
  }

  return lines.join("\n");
}

const SYSTEM_PROMPT = `You are a clinical decision support assistant generating a pre-visit provider brief. 
Analyze the de-identified chart data and produce a structured brief for the upcoming appointment.

Rules:
- All items are SUGGESTIONS for provider review — never diagnoses or orders
- Flag genuinely abnormal lab values only; do not flag normal variations
- HCC/MIPS gap suggestions must be clearly labeled as administrative/coding suggestions
- Keep each section concise — this is a one-screen brief
- Return valid JSON only, no prose outside the JSON

Output JSON with these fields:
{
  "activeProblems": string[],           // current active problem list with any recent changes noted
  "medicationChanges": string[],         // changes since last visit or notable adherence flags
  "overdueHealthMaintenance": string[], // screenings, immunizations, labs overdue
  "hccGapSuggestions": string[],        // suspected HCC codes not yet documented (admin suggestion only)
  "mipsGapSuggestions": string[],       // MIPS measure gaps (admin suggestion only)
  "priorityAlerts": string[],           // critical items requiring immediate attention
  "briefSummary": string                // 2-3 sentence plain English summary for the provider
}`;

export async function generatePreVisitBrief(
  ctx: AppointmentContext,
  chart: ChartSummaryInput
): Promise<PreVisitBrief> {
  const deidentifiedChart = deidentifyForLLM(ctx, chart);

  let parsed: Record<string, unknown>;
  try {
    const result = await chatComplete({
      messages: [
        { role: "system", content: SYSTEM_PROMPT },
        { role: "user", content: `Generate a pre-visit brief for this patient chart:\n\n${deidentifiedChart}` },
      ],
      maxOutputTokens: 2048,
      dataCategories: ["conditions", "medications", "lab_results", "vitals"],
      purpose: "clinical_decision_support",
      callerService: "pre-visit-chart-prep-service",
      callerMethod: "generatePreVisitBrief",
    });

    const jsonMatch = result.content.match(/\{[\s\S]*\}/);
    if (!jsonMatch) throw new Error("No JSON in LLM response");
    parsed = JSON.parse(jsonMatch[0]);
  } catch (err) {
    parsed = {
      activeProblems: chart.activeProblems.slice(0, 5),
      medicationChanges: [],
      overdueHealthMaintenance: [...(chart.dueScreenings || []), ...(chart.dueImmunizations || [])],
      hccGapSuggestions: [],
      mipsGapSuggestions: [],
      priorityAlerts: chart.recentLabResults
        .filter((l) => l.flag === "critical" || l.flag === "high")
        .map((l) => `Abnormal ${l.test}: ${l.value}`),
      briefSummary: `Patient scheduled for ${ctx.appointmentType} on ${ctx.appointmentDate}. Chart auto-summary unavailable — review chart manually.`,
    };
  }

  return {
    appointmentId: ctx.appointmentId,
    patientId: ctx.patientId,
    generatedAt: new Date().toISOString(),
    modelUsed: "vertex-ai-gemini-2.5-pro",
    activeProblems: (parsed.activeProblems as string[]) || [],
    medicationChanges: (parsed.medicationChanges as string[]) || [],
    overdueHealthMaintenance: (parsed.overdueHealthMaintenance as string[]) || [],
    hccGapSuggestions: (parsed.hccGapSuggestions as string[]) || [],
    mipsGapSuggestions: (parsed.mipsGapSuggestions as string[]) || [],
    priorityAlerts: (parsed.priorityAlerts as string[]) || [],
    briefSummary: (parsed.briefSummary as string) || "",
    disclaimer: DISCLAIMER,
  };
}

const briefCache = new Map<string, { brief: PreVisitBrief; cachedAt: Date }>();
const CACHE_TTL_MS = 60 * 60 * 1000;

export async function getCachedPreVisitBrief(
  ctx: AppointmentContext,
  chart: ChartSummaryInput
): Promise<PreVisitBrief> {
  const cacheKey = `${ctx.appointmentId}:${ctx.patientId}`;
  const cached = briefCache.get(cacheKey);
  if (cached && Date.now() - cached.cachedAt.getTime() < CACHE_TTL_MS) {
    return cached.brief;
  }

  const brief = await generatePreVisitBrief(ctx, chart);
  briefCache.set(cacheKey, { brief, cachedAt: new Date() });
  return brief;
}

export function invalidateBriefCache(appointmentId: string, patientId: string): void {
  briefCache.delete(`${appointmentId}:${patientId}`);
}
