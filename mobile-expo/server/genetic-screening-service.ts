export function getAllScreeningTests(): GeneticScreeningTest[] {
  return [...RUSP_CORE_CONDITIONS, ...HEARING_AND_CRITICAL_CHD, ...INTERNATIONAL_EXPANDED_SCREENING];
}

export function getScreeningByCategory(category: string): GeneticScreeningTest[] {
  return getAllScreeningTests().filter(t => t.category === category);
}

export function getScreeningByRegion(region: string): GeneticScreeningTest[] {
  return getAllScreeningTests().filter(t => t.regions.some(r => r.toLowerCase().includes(region.toLowerCase())));
}

export function getUSRUSPTests(): GeneticScreeningTest[] {
  return getAllScreeningTests().filter(t => t.usRUSP);
}

export function getInternationalTests(): GeneticScreeningTest[] {
  return getAllScreeningTests().filter(t => !t.usRUSP);
}
